#!/usr/bin/env node
// Writes typed `as const` ABIs for the web app so viem/wagmi infer every call and event.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const abi = (name) => JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8")).abi;

const target = join(root, "..", "web", "src", "lib", "abi.ts");
const body = `// Generated by contracts/scripts/export-abi.mjs — do not edit by hand.
export const pactumAbi = ${JSON.stringify(abi("Pactum"), null, 2)} as const;

export const testUsdAbi = ${JSON.stringify(abi("TestUSD"), null, 2)} as const;
`;
writeFileSync(target, body);
console.log(`wrote ${target}`);
