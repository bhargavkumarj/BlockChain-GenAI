#!/usr/bin/env node
// One command for a complete local environment:
//   pnpm devnet      → starts anvil, builds + deploys the contracts, writes web/.env.local
// then, in another terminal:
//   pnpm dev         → http://localhost:3000
//
// Requires Foundry (anvil, forge) on PATH. The keys used are anvil's well-known test keys: never reuse them.
import { spawn, spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const RPC = "http://127.0.0.1:8545";
const KEYS = {
  deployer: "0xac0974bec39a17e36ba4a6b4d238ff944bacb478cbed5efcae784d7bf4f2ff80",
  arbiter: "0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d",
  agent: "0x5de4111afa1a4b94908f83103eb1f1706367c2e68ca870fc3fb9a804cdab365a",
};

function need(bin) {
  const r = spawnSync(bin, ["--version"], { stdio: "ignore" });
  if (r.error) {
    console.error(`✗ ${bin} not found. Install Foundry: https://getfoundry.sh`);
    process.exit(1);
  }
}

async function rpcUp() {
  try {
    const res = await fetch(RPC, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "eth_chainId", params: [] }),
    });
    return res.ok;
  } catch {
    return false;
  }
}

function run(cmd, args, opts = {}) {
  const r = spawnSync(cmd, args, { stdio: "inherit", ...opts });
  if (r.status !== 0) process.exit(r.status ?? 1);
}

need("anvil");
need("forge");

let anvil;
if (await rpcUp()) {
  console.log("• Reusing the chain already running on :8545");
} else {
  console.log("• Starting anvil on :8545");
  anvil = spawn("anvil", ["--port", "8545", "--chain-id", "31337", "--silent"], { stdio: "inherit" });
  for (let i = 0; i < 50 && !(await rpcUp()); i++) await new Promise((r) => setTimeout(r, 200));
}

console.log("• Building contracts");
run("forge", ["build"], { cwd: join(root, "contracts") });
console.log("• Deploying");
run("node", ["scripts/deploy.mjs"], {
  cwd: join(root, "contracts"),
  env: { ...process.env, RPC_URL: RPC, DEPLOYER_PRIVATE_KEY: KEYS.deployer },
});
run("node", ["scripts/export-abi.mjs"], { cwd: join(root, "contracts") });

const deployment = JSON.parse(readFileSync(join(root, "contracts", "deployments", "31337.json"), "utf8"));
const envPath = join(root, "web", ".env.local");
const START = "# >>> pactum devnet (generated by scripts/devnet.mjs)";
const END = "# <<< pactum devnet";
const block = [
  START,
  "NEXT_PUBLIC_CHAIN_ID=31337",
  `NEXT_PUBLIC_RPC_URL=${RPC}`,
  `NEXT_PUBLIC_PACTUM_ADDRESS=${deployment.pactum}`,
  `NEXT_PUBLIC_USD_ADDRESS=${deployment.testUSD}`,
  `NEXT_PUBLIC_DEPLOY_BLOCK=${deployment.deployBlock}`,
  `ARBITER_PRIVATE_KEY=${KEYS.arbiter}`,
  `AGENT_PRIVATE_KEY=${KEYS.agent}`,
  END,
].join("\n");

// Keep anything the developer added (an ANTHROPIC_API_KEY or OPENROUTER_API_KEY, PINATA_JWT, …) and replace only our block.
let existing = existsSync(envPath) ? readFileSync(envPath, "utf8") : "";
existing = existing.replace(new RegExp(`${START}[\\s\\S]*?${END}\\n?`), "").trimEnd();
if (!/ANTHROPIC_API_KEY|OPENROUTER_API_KEY|AI_SIMULATE/.test(existing)) {
  existing += `${existing ? "\n\n" : ""}# Add ANTHROPIC_API_KEY=… (or OPENROUTER_API_KEY=…) for live Claude agents. Without one the deterministic simulator runs.`;
}
writeFileSync(envPath, `${existing ? `${existing}\n\n` : ""}${block}\n`);

console.log(`
✓ Local devnet ready
  Pactum   ${deployment.pactum}
  TestUSD  ${deployment.testUSD}
  web/.env.local updated

  Next: pnpm dev  →  http://localhost:3000
  (Restart \`pnpm dev\` after re-running this script: chain state resets with anvil.)
`);

if (anvil) {
  console.log("anvil is running. Press Ctrl+C to stop it.");
  const stop = () => {
    anvil.kill("SIGINT");
    process.exit(0);
  };
  process.on("SIGINT", stop);
  process.on("SIGTERM", stop);
}
